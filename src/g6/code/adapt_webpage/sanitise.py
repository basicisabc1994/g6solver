"""
sanitise — XSS-safe helpers for adapt_webpage.

Every user-supplied value that flows into generated HTML or inline ``<script>``
payloads must pass through one of these helpers first. Without them an
attacker who controls ``target``, ``color``, or ``src`` can break out of the
surrounding string literal and inject arbitrary JS (`"); alert(1); //`).

Helpers
-------
``safe_css_selector(s)``     — allow-list-restricted CSS selector (letters,
    digits, ``_ - # . > [] = " ' :( ) space``). Anything else → empty string.
``safe_color(s)``            — matches ``#rgb``, ``#rrggbb``, ``#rrggbbaa``,
    ``0xRRGGBB``, or CSS named colours. Anything else → ``"#3b82f6"``.
``safe_number(v, default)``  — coerces to a JSON-safe number; non-numbers or
    NaN/inf return ``default``.
``safe_css_length(v)``       — accepts ``\\d+(px|em|rem|%|vh|vw|pt)`` or
    a bare positive integer (coerced to px). Default fallback if invalid.
``safe_url(u)``              — accepts ``https://``, ``http://``, ``/…``, or
    ``data:application/json;…`` for Lottie. Rejects ``javascript:`` etc.
No external scripts are generated by this port."""
from __future__ import annotations

import re
from typing import Any

_SELECTOR_RE = re.compile(r"""^[A-Za-z0-9_\-#\.\[\]="':\s\(\)>,\*]+$""")
_CSS_IDENT_RE = re.compile(r"^-?[A-Za-z_][A-Za-z0-9_-]{0,63}$")
_CSS_TIME_RE = re.compile(r"^\d{1,4}(?:\.\d{1,3})?(?:ms|s)$")
_COLOR_HEX_RE = re.compile(r"^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$")
_COLOR_0X_RE = re.compile(r"^0x[0-9a-fA-F]{6}$")
_CSS_LENGTH_RE = re.compile(r"^\d{1,5}(?:\.\d{1,3})?(?:px|em|rem|%|vh|vw|pt)$")
_NAMED_COLOURS = frozenset({
    "black", "white", "red", "green", "blue", "yellow", "cyan", "magenta",
    "gray", "grey", "transparent", "inherit", "currentColor",
})
_SAFE_URL_SCHEMES = ("https://", "http://", "/")

_DEFAULT_COLOR = "#3b82f6"
_DEFAULT_SELECTOR = ".hero h1"
_DEFAULT_EASING = "ease-out"
_SAFE_EASINGS = frozenset({
    "linear", "ease", "ease-in", "ease-out", "ease-in-out",
    "step-start", "step-end",
})


def safe_css_selector(s: str, *, default: str = _DEFAULT_SELECTOR) -> str:
    s = (s or "").strip()
    if not s:
        return default
    if not _SELECTOR_RE.match(s) or len(s) > 256:
        return default
    # Reject anything with a stray quote / backslash pattern that could
    # escape a JS string — the allow-list above already blocks these, but
    # double-check to be explicit.
    if any(c in s for c in ('"', "\\")):
        return default
    return s


def safe_color(s: str, *, default: str = _DEFAULT_COLOR) -> str:
    s = (s or "").strip()
    if not s:
        return default
    if _COLOR_HEX_RE.match(s) or _COLOR_0X_RE.match(s):
        return s
    if s.lower() in _NAMED_COLOURS:
        return s
    return default


def safe_css_identifier(s: str, *, default: str = "fadeIn") -> str:
    s = (s or "").strip()
    if not s:
        return default
    if _CSS_IDENT_RE.match(s):
        return s
    return default


def safe_css_time(s: Any, *, default: str = "0.6s") -> str:
    value = str(s or "").strip()
    if value and _CSS_TIME_RE.match(value):
        return value
    return default


def safe_css_easing(s: Any, *, default: str = _DEFAULT_EASING) -> str:
    value = str(s or "").strip()
    if value in _SAFE_EASINGS:
        return value
    return default


def safe_angle(v: Any, *, default: int = 135) -> int:
    n = safe_number(v, default)
    try:
        return max(0, min(360, int(n)))
    except (TypeError, ValueError):
        return default


def safe_style_block(css: str) -> str:
    """Keep user CSS inside its enclosing ``<style>`` tag.

    Custom CSS is still allowed, but HTML raw-text closing tags are escaped so
    a stylesheet cannot break out into executable markup.
    """
    value = str(css or "").replace("\x00", "")
    value = re.sub(
        r"</\s*(style|script)",
        lambda match: f"<\\/{match.group(1)}",
        value,
        flags=re.IGNORECASE,
    )
    return value


def safe_number(v: Any, default: float | int) -> float | int:
    try:
        n = float(v)
    except (TypeError, ValueError):
        return default
    if n != n or n in (float("inf"), float("-inf")):
        return default
    return int(n) if isinstance(default, int) and n.is_integer() else n


def safe_css_length(v: Any, *, default: str = "300px") -> str:
    if isinstance(v, (int, float)):
        return f"{int(v)}px"
    s = str(v or "").strip()
    if not s:
        return default
    if _CSS_LENGTH_RE.match(s):
        return s
    if s.isdigit():
        return f"{s}px"
    return default


def safe_url(u: str, *, default: str = "") -> str:
    u = (u or "").strip()
    if not u:
        return default
    if any(u.startswith(p) for p in _SAFE_URL_SCHEMES):
        # Still reject embedded quotes/angle brackets — they'd break out of
        # the enclosing attribute string.
        if any(c in u for c in ('"', "'", "<", ">", "\n", "\r")):
            return default
        return u
    return default


