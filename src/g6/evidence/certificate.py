"""The certificate issuer: the one place a mission's completion state is decided (CSIR tex:498-531, 1076-1100).

``issue`` takes the mission as values (``MissionFacts``: its hash, its predicates, its gates, the soundness obligations it
breaks, its cost bound and the catalogue hash it was judged against; the research rig computes them with the CSIR judgement,
the workforce from its own plan checks) and is bound to the frozen standard: the mission's standard hash must be that
standard's hash, and its predicates that standard's predicates. Moved here from the research rig (RVC R6.1) so the product
and the research rig share one issuer; the rig adapts its own types to it (nothing here depends on the rig).

Each predicate gets a Belnap value ``(support, refute)`` from ``B4 = {(0,0), (1,0), (0,1), (1,1)}``, built only from receipts
taken on the exact artifact bytes. Deciding ``verified`` is deliberately not monotone in the evidence: one refutation turns
support into a conflict, and a conflict is never averaged away.

A receipt **supports** predicate ``p`` only if its check meets, for ``p``, the A4 grounding rule (plan gap 6; founder ruling
D2, 2026-10-14, which lets a check written by the customer's agent reach A4 under exactly these conditions):

- evidence kind ``independent_executable`` or ``formal_checked``; a formal check also names its certificate digest;
- the check's author is not the artifact's producer (obligation A5);
- the check was frozen before the artifact existed;
- a negative control for ``p`` and for this check's code (its hash), generated by G6, was killed by the check, and recorded at
  or after the freeze and before the receipt it backs (gap 3: ``covers(c, p)`` needs a control that instantiates ``p``);
- the receipt was taken once the artifact existed, and names the check's frozen hash and the artifact's hash;
- the receipt, and a control that backs it, are entries of the ``g6.core.ledger.ChainLedger`` passed as ``ledger``, found
  by kind (``control`` / ``receipt``), id and body hash (EVIDENCE-01). G6's runners write what they observed there with
  ``record``. A record the ledger does not hold, or holds with another body, is named in the gaps and in
  ``unresolved``, and the predicate stays unsupported: fields a caller typed (``generated_by="g6"``, ``killed=True``,
  ``"pass"``) never reach ``verified`` on their own. The ledger is only as honest as what writes to it: a caller that
  appends forged entries to a ledger it builds itself is outside what this catches, but it has to forge a
  hash-chained record a reviewer can audit, not a field.

A failing receipt **refutes** ``p`` only if its check has shown both that it can fail on ``p`` (such a control, killed,
before the receipt) and that it passes a known-good reference (``positive_seq``, before the receipt): an always-failing check
kills every control, so without the positive control its failures say nothing about the artifact. Any other failure, and
any ``unknown`` result, is a caveat: it keeps ``p`` from verified but is not a refutation.

The state: ``blocked-escalated`` if the mission breaks a soundness obligation (C1 does not apply) or any predicate is
refuted; ``verified`` if every predicate is supported with no caveat and every gate was decided (a decision is necessary,
never sufficient); otherwise ``qualified-draft``. Every predicate that is not verified is named in ``gaps`` (S2). The
certificate states the mission's cost bound, and an unknown cost as unknown (S4).

The three certificates are kept apart and cannot be laundered: ``receipts`` (what ran, on which bytes), the predicate
statements (what the evidence supports) and ``formal`` (only predicates whose support is a formal check with a certificate).

``verify`` (S5) is scoped to what can be checked. The digest is unkeyed, so a forger can recompute it; what makes a forgery
fail is consistency. The certificate records what its state was decided from (the artifact's ledger position, the checks
with their controls, the mission's gates and the obligations it breaks), and ``verify`` runs ``issue`` again on those
records and names every field that differs, so a state, statement, gap, formal list or re-run list that does not follow by
the issuing rules is caught even when all of them were rewritten together. Given the ledger, it resolves the records
again; without it, it takes the certificate's own ``unresolved`` list (consistency only). Offline it also checks the
artifact bytes and the certificate's own consistency; given the mission and the standard as well, it catches a dropped
predicate, a dropped gate gap, and a changed mission or standard hash. A certificate that does not record its checks cannot be decided again,
and ``verify`` says so. Nothing here proves that the recorded producer, authors, kinds, positions, controls, receipts,
gates, obligations and decisions are true; that is the job of the ledger and the runner that write them (and of a verifier
that also holds the frozen checks).
"""
from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Callable, Collection, Mapping, Sequence
from dataclasses import asdict, dataclass
from typing import Any

from g6.core.ledger import ChainLedger
from g6.core.ledger import digest as _ledger_digest

G6 = "g6"
#: The ledger kinds G6 writes a control and a receipt under (``record``) and the issuer resolves them from.
CONTROL_KIND, RECEIPT_KIND = "control", "receipt"
EVIDENCE_KINDS = ("process", "heuristic_review", "partial_falsifier", "independent_executable", "formal_checked",
                  "no_evidence")
A4_KINDS = ("independent_executable", "formal_checked")
RESULTS = ("pass", "fail", "unknown")
STATES = ("verified", "qualified-draft", "blocked-escalated")
#: v2 records what the state was decided from, so ``verify`` can decide it again.
SCHEMA = "csir_certificate.v2"
_HEX64 = re.compile(r"[0-9a-f]{64}\Z")
_ADVISORY = "advisory_check_failed"
_UNKNOWN = "check_result_unknown"


class CertificateRefused(ValueError):
    """The inputs contradict one another or the mission; nothing is judged from them."""

    def __init__(self, problems: Sequence[str]) -> None:
        self.problems = tuple(problems)
        super().__init__("; ".join(self.problems))


def _position(value: Any, where: str) -> None:
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise CertificateRefused([f"{where}: a ledger position must be a whole number, 0 or more"])


@dataclass(frozen=True)
class Control:
    """A negative control: a seeded defect for one predicate, run against one version of a check's code."""

    control_id: str
    check_sha: str
    predicate: str
    generated_by: str
    seq: int
    killed: bool

    def __post_init__(self) -> None:
        _position(self.seq, f"control {self.control_id!r}")


@dataclass(frozen=True)
class Check:
    check_id: str
    predicates: tuple[str, ...]
    author: str
    kind: str
    check_sha: str
    #: Ledger position at which the check's code was frozen.
    frozen_seq: int
    controls: tuple[Control, ...] = ()
    #: A formal check's certificate digest ("" for any other kind).
    certificate: str = ""
    #: Ledger position at which the check passed a known-good reference (None when no reference existed).
    positive_seq: int | None = None

    def __post_init__(self) -> None:
        problems = []
        if self.kind not in EVIDENCE_KINDS:
            problems.append(f"check {self.check_id!r}: kind must be one of {EVIDENCE_KINDS}")
        if not _HEX64.match(self.check_sha):
            problems.append(f"check {self.check_id!r}: check_sha must be a sha256 hex digest")
        if not self.predicates:
            problems.append(f"check {self.check_id!r}: names no predicate")
        if self.certificate and not _HEX64.match(self.certificate):
            problems.append(f"check {self.check_id!r}: certificate must be a sha256 hex digest")
        if not self.author.strip():
            problems.append(f"check {self.check_id!r}: author is required")
        if problems:
            raise CertificateRefused(problems)
        _position(self.frozen_seq, f"check {self.check_id!r}")
        if self.positive_seq is not None:
            _position(self.positive_seq, f"check {self.check_id!r} positive control")


@dataclass(frozen=True)
class Receipt:
    receipt_id: str
    check_id: str
    check_sha: str
    artifact_sha: str
    result: str
    seq: int

    def __post_init__(self) -> None:
        if self.result not in RESULTS:
            raise CertificateRefused([f"receipt {self.receipt_id!r}: result must be one of {RESULTS}"])
        _position(self.seq, f"receipt {self.receipt_id!r}")


@dataclass(frozen=True)
class Artifact:
    sha256: str
    producer: str
    #: Ledger position at which the artifact was recorded.
    seq: int

    def __post_init__(self) -> None:
        _position(self.seq, "artifact")


@dataclass(frozen=True)
class PredicateStatement:
    predicate: str
    support: bool
    refute: bool
    supported_by: tuple[str, ...]
    refuted_by: tuple[str, ...]
    #: Checks whose failure or unknown result keeps the predicate from verified without refuting it.
    caveats: tuple[str, ...]

    @property
    def verified(self) -> bool:
        return self.support and not self.refute and not self.caveats

    def as_dict(self) -> dict[str, Any]:
        return {"predicate": self.predicate, "support": self.support, "refute": self.refute,
                "supported_by": list(self.supported_by), "refuted_by": list(self.refuted_by), "caveats": list(self.caveats)}


def _controls(check: Check, predicate: str) -> list[Control]:
    return [c for c in check.controls if c.predicate == predicate]


def _sound_control(check: Check, control: Control) -> bool:
    return (control.generated_by == G6 and control.killed and control.check_sha == check.check_sha
            and control.seq >= check.frozen_seq)


def grounding(check: Check, artifact: Artifact, predicate: str) -> tuple[str, ...]:
    """Why ``check`` is not A4 for ``predicate`` on ``artifact`` (empty when it is). Receipt order is judged per receipt."""
    reasons = []
    if check.kind not in A4_KINDS:
        reasons.append("evidence_kind")
    if check.kind == "formal_checked" and not check.certificate:
        reasons.append("formal_without_certificate")
    if check.author == artifact.producer:
        reasons.append("self_authored")
    if check.frozen_seq >= artifact.seq:
        reasons.append("frozen_after_artifact")
    controls = _controls(check, predicate)
    if not controls:
        reasons.append("no_negative_control")
    elif not any(_sound_control(check, c) for c in controls):
        found = {"control_not_generated_by_g6": any(c.generated_by != G6 for c in controls),
                 "control_not_killed": any(not c.killed for c in controls),
                 "control_for_other_code": any(c.check_sha != check.check_sha for c in controls),
                 "control_before_freeze": any(c.seq < check.frozen_seq for c in controls)}
        reasons += [name for name, hit in found.items() if hit]
    return tuple(reasons)


def _backing(check: Check, predicate: str, receipt: Receipt) -> bool:
    """A sound control for ``predicate`` recorded before ``receipt``: the check had shown it can fail there."""
    return any(_sound_control(check, c) and c.seq < receipt.seq for c in _controls(check, predicate))


#: ``resolves(kind, id, body)``: whether the ledger holds that record with that body.
_Resolves = Callable[[str, str, Mapping[str, Any]], bool]


def record(ledger: ChainLedger, *records: Control | Receipt) -> None:
    """Write controls and receipts G6 observed into ``ledger``, so ``issue`` can resolve them by id and hash."""
    for item in records:
        if isinstance(item, Control):
            ledger.append(CONTROL_KIND, item.control_id, asdict(item))
        elif isinstance(item, Receipt):
            ledger.append(RECEIPT_KIND, item.receipt_id, asdict(item))
        else:
            raise TypeError(f"only a Control or a Receipt is recorded, not {type(item).__name__}")


def _resolver(ledger: ChainLedger | None) -> _Resolves:
    """Resolution against ``ledger``: an entry of that kind and id whose body hash is the record's. No ledger, none."""
    def resolves(kind: str, ident: str, body: Mapping[str, Any]) -> bool:
        if ledger is None:
            return False
        try:
            return ledger.entry(kind, ident)["body_sha256"] == _ledger_digest(dict(body))
        except (KeyError, ValueError):
            return False
    return resolves


def _unresolved(check: Check, predicate: str, receipt: Receipt, resolves: _Resolves) -> list[tuple[str, str]]:
    """The records a support of ``predicate`` by ``receipt`` would rest on that the ledger does not hold: the receipt,
    and every backing control when none of them resolves."""
    missing = [] if resolves(RECEIPT_KIND, receipt.receipt_id, asdict(receipt)) else [
        (RECEIPT_KIND, receipt.receipt_id)]
    backing = [c for c in _controls(check, predicate) if _sound_control(check, c) and c.seq < receipt.seq]
    if not any(resolves(CONTROL_KIND, c.control_id, asdict(c)) for c in backing):
        missing += [(CONTROL_KIND, c.control_id) for c in backing]
    return missing


def catalogue_sha(catalogue: Mapping[str, Any]) -> str:
    """The hash of the catalogue a mission was judged against (op, effect, class), recorded on the certificate."""
    rows = sorted((op, fact.effect, fact.authority) for op, fact in catalogue.items())
    return hashlib.sha256(json.dumps(rows, separators=(",", ":")).encode("utf-8")).hexdigest()


@dataclass(frozen=True)
class Certificate:
    mission_sha: str
    standard_sha: str
    catalogue_sha: str
    artifact_sha: str
    producer: str
    state: str
    predicates: tuple[PredicateStatement, ...]
    gaps: tuple[tuple[str, str], ...]
    receipts: tuple[Receipt, ...]
    formal: tuple[tuple[str, str, str], ...]
    #: (check id, check hash, evidence kind) of every check the support rests on: what to re-run, and what kind it is.
    rerun: tuple[tuple[str, str, str], ...]
    violations: tuple[str, ...]
    decisions: tuple[str, ...]
    #: The mission's cost bound in cents; ``None`` is unknown and is shown as unknown, never as zero.
    cost_cents: int | None
    solvability: Mapping[str, Any] | None
    #: What the state was decided from, recorded so ``verify`` can decide it again: the artifact's ledger position, the
    #: checks (with their controls), the mission's gates and the obligations it breaks as (obligation, code, detail).
    artifact_seq: int | None = None
    checks: tuple[Check, ...] = ()
    gates: tuple[str, ...] = ()
    obligations: tuple[tuple[str, str, str], ...] = ()
    #: (kind, id) of every control and receipt a support would rest on that the ledger did not hold (EVIDENCE-01).
    unresolved: tuple[tuple[str, str], ...] = ()

    @property
    def verified_predicates(self) -> tuple[str, ...]:
        return tuple(s.predicate for s in self.predicates if s.verified)

    def as_dict(self) -> dict[str, Any]:
        body: dict[str, Any] = {
            "schema": SCHEMA, "mission_sha": self.mission_sha, "standard_sha": self.standard_sha,
            "catalogue_sha": self.catalogue_sha, "artifact_sha": self.artifact_sha, "producer": self.producer,
            "state": self.state, "predicates": [s.as_dict() for s in self.predicates], "gaps": [list(g) for g in self.gaps],
            "receipts": [{"receipt_id": r.receipt_id, "check_id": r.check_id, "check_sha": r.check_sha,
                          "artifact_sha": r.artifact_sha, "result": r.result, "seq": r.seq} for r in self.receipts],
            "formal": [list(f) for f in self.formal], "rerun": [list(r) for r in self.rerun],
            "violations": list(self.violations), "decisions": list(self.decisions), "cost_cents": self.cost_cents,
            "solvability": dict(self.solvability) if self.solvability else None,
            "artifact_seq": self.artifact_seq, "checks": [_check_dict(c) for c in self.checks],
            "gates": list(self.gates), "obligations": [list(o) for o in self.obligations],
            "unresolved": [list(u) for u in self.unresolved]}
        body["digest"] = digest_of(body)
        return body


def _check_dict(c: Check) -> dict[str, Any]:
    return {"check_id": c.check_id, "predicates": list(c.predicates), "author": c.author, "kind": c.kind,
            "check_sha": c.check_sha, "frozen_seq": c.frozen_seq, "certificate": c.certificate,
            "positive_seq": c.positive_seq,
            "controls": [{"control_id": k.control_id, "check_sha": k.check_sha, "predicate": k.predicate,
                          "generated_by": k.generated_by, "seq": k.seq, "killed": k.killed} for k in c.controls]}


def _check_of(raw: Mapping[str, Any]) -> Check:
    controls = tuple(Control(**k) for k in raw["controls"])
    return Check(**{**raw, "predicates": tuple(raw["predicates"]), "controls": controls})


def digest_of(body: Mapping[str, Any]) -> str:
    """The certificate's digest: sha256 of its canonical JSON without the digest field (unkeyed; see ``verify``)."""
    text = json.dumps({k: v for k, v in body.items() if k != "digest"}, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


@dataclass(frozen=True)
class MissionFacts:
    """What the issuer needs to know about the mission, as values (the workforce and the research rig each supply them).

    ``violations`` are the soundness obligations the mission breaks, as (obligation, code, detail); an empty tuple means
    the mission passed its plan checks (CSIR C1 applies)."""

    mission_sha: str
    #: The hash the mission cites for its standard, and the frozen standard's own hash: they must be equal.
    mission_standard_sha: str
    standard_sha: str
    predicates: tuple[str, ...]
    standard_predicates: tuple[str, ...]
    gates: tuple[str, ...] = ()
    violations: tuple[tuple[str, str, str], ...] = ()
    cost_cents: int | None = None
    catalogue_sha: str = ""


def _refusals(facts: MissionFacts, artifact: Artifact, checks: Sequence[Check],
              receipts: Sequence[Receipt], decisions: Collection[str]) -> list[str]:
    problems = []
    if facts.mission_standard_sha != facts.standard_sha:
        problems.append("the mission's standard hash is not the frozen standard's hash")
    elif set(facts.predicates) != set(facts.standard_predicates):
        problems.append("the mission lists other predicates than its frozen standard has")
    if not _HEX64.match(artifact.sha256) or not artifact.producer.strip():
        problems.append("the artifact needs a sha256 and a producer")
    ids = [c.check_id for c in checks]
    problems += [f"duplicate check id {i!r}" for i in sorted({i for i in ids if ids.count(i) > 1})]
    rids = [r.receipt_id for r in receipts]
    problems += [f"duplicate receipt id {i!r}" for i in sorted({i for i in rids if rids.count(i) > 1})]
    known = set(facts.predicates)
    for c in checks:
        problems += [f"check {c.check_id!r} names predicate {p!r}, which is not in the standard"
                     for p in c.predicates if p not in known]
    problems += [f"receipt {r.receipt_id!r} names check {r.check_id!r}, which nobody froze"
                 for r in receipts if r.check_id not in set(ids)]
    gates = set(facts.gates)
    problems += [f"a decision names {d!r}, which is no gate of this mission" for d in sorted(set(decisions) - gates)]
    return problems


def issue(facts: MissionFacts, artifact: Artifact, checks: Sequence[Check], receipts: Sequence[Receipt], *,
          decisions: Collection[str] = (), solvability: Mapping[str, Any] | None = None,
          ledger: ChainLedger | None = None) -> Certificate:
    """The certificate for ``artifact`` under the mission ``facts``; or ``CertificateRefused`` listing every problem with
    what it was given. ``ledger`` holds the controls and receipts G6 observed (``record``); without it nothing is
    resolved, so nothing is supported and the state is at best ``qualified-draft``."""
    return _issue(facts, artifact, checks, receipts, decisions, solvability, _resolver(ledger))


def _issue(facts: MissionFacts, artifact: Artifact, checks: Sequence[Check], receipts: Sequence[Receipt],
           decisions: Collection[str], solvability: Mapping[str, Any] | None, resolves: _Resolves) -> Certificate:
    problems = _refusals(facts, artifact, checks, receipts, decisions)
    if problems:
        raise CertificateRefused(problems)
    by_id = {c.check_id: c for c in checks}
    keys = facts.predicates
    support: dict[str, list[str]] = {p: [] for p in keys}
    refute: dict[str, list[str]] = {p: [] for p in keys}
    caveat: dict[str, list[str]] = {p: [] for p in keys}
    notes: dict[str, list[str]] = {p: [] for p in keys}
    unresolved: set[tuple[str, str]] = set()
    for r in sorted(receipts, key=lambda r: (r.seq, r.receipt_id)):
        c = by_id[r.check_id]
        for p in c.predicates:
            if r.artifact_sha != artifact.sha256:
                notes[p].append(f"receipt_for_other_bytes:{r.receipt_id}")
            elif r.check_sha != c.check_sha:
                notes[p].append(f"check_changed_after_freeze:{c.check_id}")
            elif r.seq < artifact.seq:
                notes[p].append(f"receipt_before_artifact:{r.receipt_id}")
            elif r.result == "pass":
                reasons = grounding(c, artifact, p)
                if reasons:
                    notes[p].append(f"not_grounded:{c.check_id}:{','.join(reasons)}")
                elif not _backing(c, p, r):
                    notes[p].append(f"control_after_receipt:{c.check_id}")
                elif missing := _unresolved(c, p, r, resolves):
                    # EVIDENCE-01: a record G6's ledger does not hold is a caller's word, never support.
                    unresolved.update(missing)
                    notes[p].append(f"not_in_ledger:{c.check_id}:" + ",".join(f"{k}:{i}" for k, i in missing))
                else:
                    support[p].append(c.check_id)
            elif r.result == "fail":
                if _backing(c, p, r) and c.positive_seq is not None and c.positive_seq < r.seq:
                    refute[p].append(c.check_id)
                else:
                    caveat[p].append(c.check_id)
                    notes[p].append(f"{_ADVISORY}:{c.check_id}")
            else:
                caveat[p].append(c.check_id)
                notes[p].append(f"{_UNKNOWN}:{c.check_id}")
    statements = tuple(PredicateStatement(p, bool(support[p]), bool(refute[p]), tuple(dict.fromkeys(support[p])),
                                          tuple(dict.fromkeys(refute[p])), tuple(dict.fromkeys(caveat[p])))
                       for p in keys)
    gaps: list[tuple[str, str]] = []
    for s in statements:
        if s.verified:
            continue
        why = list(dict.fromkeys(notes[s.predicate]))
        if s.refute:
            why.insert(0, "refuted_by:" + ",".join(s.refuted_by))
        gaps.append((f"predicate:{s.predicate}", ";".join(why) or "no_receipt"))
    gaps += [(f"gate:{g}", "human_decision_missing") for g in facts.gates if g not in decisions]
    gaps += [(f"obligation:{o}", f"{code}: {detail}") for o, code, detail in facts.violations]
    codes = tuple(sorted({code for _, code, _ in facts.violations}))
    state = _state(bool(codes), statements, any(g.startswith("gate:") for g, _ in gaps))
    formal = tuple(sorted({(s.predicate, cid, by_id[cid].certificate) for s in statements if s.verified
                           for cid in s.supported_by if by_id[cid].kind == "formal_checked"}))
    rerun = tuple(sorted({(cid, by_id[cid].check_sha, by_id[cid].kind) for s in statements for cid in s.supported_by}))
    return Certificate(
        mission_sha=facts.mission_sha, standard_sha=facts.standard_sha, catalogue_sha=facts.catalogue_sha,
        artifact_sha=artifact.sha256, producer=artifact.producer, state=state, predicates=statements, gaps=tuple(gaps),
        receipts=tuple(receipts), formal=formal, rerun=rerun, violations=codes,
        decisions=tuple(sorted(set(decisions))), cost_cents=facts.cost_cents,
        solvability=dict(solvability) if solvability else None, artifact_seq=artifact.seq, checks=tuple(checks),
        gates=tuple(facts.gates), obligations=tuple(tuple(v) for v in facts.violations),
        unresolved=tuple(sorted(unresolved)))


def _state(unsound: bool, statements: Sequence[PredicateStatement], undecided: bool) -> str:
    if unsound or any(s.refute for s in statements):
        return "blocked-escalated"
    if statements and all(s.verified for s in statements) and not undecided:
        return "verified"
    return "qualified-draft"


def _statement(raw: Mapping[str, Any]) -> PredicateStatement:
    for name in ("support", "refute"):
        if not isinstance(raw[name], bool):
            raise TypeError(f"{name} must be true or false")
    lists = [raw[name] for name in ("supported_by", "refuted_by", "caveats")]
    if not all(isinstance(x, list) and all(isinstance(i, str) for i in x) for x in lists):
        raise TypeError("supported_by, refuted_by and caveats must be lists of check ids")
    return PredicateStatement(str(raw["predicate"]), raw["support"], raw["refute"], *(tuple(x) for x in lists))


def verify(body: Mapping[str, Any], artifact_bytes: bytes, *, mission_sha: str | None = None,
           predicates: Sequence[str] | None = None, gates: Sequence[str] | None = None, standard_sha: str | None = None,
           standard_predicates: Sequence[str] | None = None, ledger: ChainLedger | None = None) -> list[str]:
    """Every inconsistency found in the certificate ``body`` for ``artifact_bytes`` (empty when none is found).

    Offline it checks the bytes and the certificate's internal consistency, and decides the certificate again from the
    checks, receipts, gates and obligations it records, naming every field that differs; given the mission's facts (its
    hash, predicates and gates) and the standard's (its hash and predicates) it also checks the certificate against them.
    Given the ``ledger`` its records were written to, the decision resolves them there again; without it, it takes the
    certificate's own ``unresolved`` list. Without the ledger it cannot tell whether what the certificate records was
    honestly recorded (see the module docstring)."""
    problems = []
    if body.get("digest") != digest_of(body):
        problems.append("the digest does not match the certificate's contents")
    if hashlib.sha256(artifact_bytes).hexdigest() != body.get("artifact_sha"):
        problems.append("the artifact bytes are not the ones the certificate was issued for")
    try:
        statements = [_statement(s) for s in body["predicates"]]
        gaps = [tuple(g) for g in body["gaps"]]
        named = {str(subject) for subject, _ in gaps}
        receipts = list(body["receipts"])
        undecided = any(subject.startswith("gate:") for subject in named)
        expected = _state(bool(body["violations"]), statements, undecided)
        if body.get("state") != expected:
            problems.append(f"the state {body.get('state')!r} does not follow from the certificate's statements ({expected!r})")
        problems += [f"predicate {s.predicate!r} is not verified and not named in the gaps" for s in statements
                     if not s.verified and f"predicate:{s.predicate}" not in named]
        problems += [f"predicate {s.predicate!r}: its support and refutation flags disagree with the checks it names"
                     for s in statements if s.support != bool(s.supported_by) or s.refute != bool(s.refuted_by)]
        on_bytes = [r for r in receipts if r["artifact_sha"] == body.get("artifact_sha")]
        passed = {r["check_id"]: r["check_sha"] for r in on_bytes if r["result"] == "pass"}
        failed = {r["check_id"] for r in on_bytes if r["result"] == "fail"}
        for s in statements:
            problems += [f"predicate {s.predicate!r} names support from {cid!r}, which has no pass receipt on these bytes"
                         for cid in s.supported_by if cid not in passed]
            problems += [f"predicate {s.predicate!r} names a refutation from {cid!r}, which has no fail receipt on these "
                         "bytes" for cid in s.refuted_by if cid not in failed]
        rerun = {str(r[0]): (str(r[1]), str(r[2])) for r in body["rerun"]}
        supported = {(cid, passed.get(cid, "")) for s in statements for cid in s.supported_by}
        if {(cid, sha) for cid, (sha, _) in rerun.items()} != supported or len(rerun) != len(body["rerun"]):
            problems.append("the re-run list is not exactly the checks the support rests on")
        problems += [f"check {cid!r} supports a predicate but is of kind {kind!r}, which cannot"
                     for cid, (_, kind) in sorted(rerun.items()) if kind not in A4_KINDS]
        formal_support = {(s.predicate, cid) for s in statements if s.verified for cid in s.supported_by
                          if rerun.get(cid, ("", ""))[1] == "formal_checked"}
        if {(str(f[0]), str(f[1])) for f in body["formal"]} != formal_support:
            problems.append("the formal certificate is not exactly the verified support from formal checks")
        obligation_gaps = {subject for subject in named if subject.startswith("obligation:")}
        if bool(body["violations"]) != bool(obligation_gaps):
            problems.append("the recorded violations and the obligation gaps disagree")
        if mission_sha is not None and body.get("mission_sha") != mission_sha:
            problems.append("the certificate is for another mission")
        if predicates is not None and {s.predicate for s in statements} != set(predicates):
            problems.append("the certificate's predicates are not the mission's")
        if gates is not None:
            missing = {f"gate:{g}" for g in gates if g not in set(body["decisions"])} - named
            problems += [f"{gate} was not decided and is not named in the gaps" for gate in sorted(missing)]
        if standard_sha is not None and body.get("standard_sha") != standard_sha:
            problems.append("the certificate is under another standard")
        if standard_predicates is not None and {s.predicate for s in statements} != set(standard_predicates):
            problems.append("the certificate's predicates are not the standard's")
        problems += _decided_again(body, tuple(s.predicate for s in statements), ledger)
    except (KeyError, TypeError, ValueError, IndexError) as exc:
        problems.append(f"the certificate is not readable: {exc}")
    return problems


def _decided_again(body: Mapping[str, Any], predicates: tuple[str, ...], ledger: ChainLedger | None) -> list[str]:
    """Run ``issue`` again on what the certificate records and name every field of the result that differs from it."""
    if body.get("schema") != SCHEMA:
        return [f"the certificate is {body.get('schema')!r}, which does not record the checks it was issued from, so "
                "its state cannot be decided again"]
    if ledger is not None:
        resolves = _resolver(ledger)
    else:  # offline: the certificate's own account of what its ledger did not hold (consistency only)
        recorded = {(str(kind), str(ident)) for kind, ident in body.get("unresolved", [])}

        def resolves(kind: str, ident: str, _body: Mapping[str, Any]) -> bool:
            return (kind, ident) not in recorded
    facts = MissionFacts(mission_sha=body["mission_sha"], mission_standard_sha=body["standard_sha"],
                         standard_sha=body["standard_sha"], predicates=predicates, standard_predicates=predicates,
                         gates=tuple(body["gates"]), violations=tuple(tuple(o) for o in body["obligations"]),
                         cost_cents=body["cost_cents"], catalogue_sha=body["catalogue_sha"])
    try:
        artifact = Artifact(body["artifact_sha"], body["producer"], body["artifact_seq"])
        checks = [_check_of(c) for c in body["checks"]]
        receipts = [Receipt(**r) for r in body["receipts"]]
        again = _issue(facts, artifact, checks, receipts, body["decisions"], body["solvability"], resolves).as_dict()
    except CertificateRefused as refused:
        return [f"the issuer refuses what the certificate records: {refused}"]
    differ = sorted(k for k in set(again) | set(body) if k != "digest" and again.get(k) != body.get(k))
    if differ:
        return [f"the certificate does not follow from the checks and receipts it records by the issuing rules "
                f"({', '.join(differ)} differ)"]
    return []
