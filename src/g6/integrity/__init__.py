"""g6.integrity — do the files under a root match a manifest of their SHA-256 hashes? (audit 020 §11)

Capability label: ``implemented``.

    from g6.integrity import build_manifest, verify_tree
    manifest = build_manifest("path/to/release")          # at release time; keep it, and its digest, elsewhere
    result = verify_tree("path/to/install", manifest, expected_manifest_sha256=PINNED)

What a match establishes: these bytes are the ones the manifest lists. Whether the manifest itself can be trusted is
the caller's: a manifest kept next to the code it covers can be regenerated by whoever changed the code (IS-003). So a
match is ``verified`` only when the manifest's own digest was pinned by the caller (a release artefact, a signed
note) and equals it, and G6's re-check (``g6.integrity.tree``) reproduces the match from the files, against that pin,
whenever the label is read; an unpinned match is a ``qualified-draft``. Only ``verify_tree`` makes a result G6 will
re-check (it seals the root, manifest, pin and patterns its caller gave), so a result built by hand, one that brings
its own pin, or a tree changed after the check is never ``verified``; a re-check that finds a mismatch, or cannot read
the files, makes it ``blocked-escalated``. No manifest, a mismatch, or a wrong pin is
``blocked-escalated``, and ``manifest_present`` says which (IS-004). There is no "regenerate" command, and nothing here
suppresses a finding. :func:`verify_installed` checks the code that is running (the installed ``g6`` package), not a
copy in some workspace.
"""
from __future__ import annotations

import hashlib
import os
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build_manifest(root: str | os.PathLike[str], *, patterns: tuple[str, ...] = ("**/*.py",)) -> dict[str, str]:
    """``relative/posix/path -> sha256`` for every file under ``root`` matching ``patterns`` (``__pycache__`` skipped)."""
    base = Path(root)
    found = {p for pattern in patterns for p in base.glob(pattern) if p.is_file() and "__pycache__" not in p.parts}
    return {p.relative_to(base).as_posix(): _sha(p.read_bytes()) for p in sorted(found)}


def manifest_text(manifest: Mapping[str, str]) -> str:
    return "".join(f"{digest}  {path}\n" for path, digest in sorted(manifest.items()))


def manifest_sha256(manifest: Mapping[str, str]) -> str:
    """The digest to pin: of the manifest's canonical text."""
    return _sha(manifest_text(manifest).encode("utf-8"))


def write_manifest(manifest: Mapping[str, str], path: str | os.PathLike[str]) -> str:
    """Write ``hash  path`` lines; returns the manifest's digest (the value to pin)."""
    Path(path).write_text(manifest_text(manifest), encoding="utf-8")
    return manifest_sha256(manifest)


def read_manifest(path: str | os.PathLike[str]) -> dict[str, str]:
    """The manifest at ``path``; an absent file is an empty manifest (``verify_tree`` reports it as absent)."""
    target = Path(path)
    if not target.is_file():
        return {}
    out = {}
    for line in target.read_text(encoding="utf-8").splitlines():
        digest, sep, rel = line.partition("  ")
        if sep and len(digest) == 64:
            out[rel] = digest
    return out


@dataclass(frozen=True)
class IntegrityResult:
    manifest_present: bool
    matched: bool
    pinned: bool                 # the caller pinned the manifest's digest and it is equal
    missing: tuple[str, ...]     # listed but not on disk
    modified: tuple[str, ...]    # on disk with other bytes
    unexpected: tuple[str, ...]  # on disk, matching the patterns, not listed
    problems: tuple[str, ...]
    # What G6 re-checks when the label is read (g6.integrity.tree): the resolved root, the manifest as sorted
    # (path, digest) pairs, the pin and the patterns. A result built without them has nothing to re-check.
    root: str = ""
    manifest: tuple[tuple[str, str], ...] = ()
    expected_manifest_sha256: str = ""
    patterns: tuple[str, ...] = ("**/*.py",)
    # verify_tree's seal over what its caller gave (root, manifest, pin, patterns); a result built any other way has
    # none, so there is nothing G6 can re-check it against.
    seal: str = field(default="", repr=False, compare=False)

    def recheck(self) -> tuple[str, str]:
        """``(label, why)``: ``verified`` only when G6's re-check reproduces the pinned match from the files now,
        against the pin ``verify_tree``'s caller gave; the fields alone are the result's own claim. Never raises."""
        if not self.matched:
            return "blocked-escalated", "; ".join(self.problems) or "the files did not match the manifest"
        if not self.pinned:
            return "qualified-draft", "the manifest is not pinned"
        if self.seal != _seal(self.root, self.manifest, self.expected_manifest_sha256, self.patterns):
            return "qualified-draft", ("this result was not made by verify_tree with its caller's pin, so G6 has "
                                       "nothing to re-check it against")
        from g6.integrity import tree

        label, why, _identity = tree.recheck(self.root, dict(self.manifest), self.expected_manifest_sha256,
                                             self.patterns)
        return label, why

    @property
    def reliability_label(self) -> str:
        return self.recheck()[0]


def _seal(root: str, manifest: tuple[tuple[str, str], ...], pin: str, patterns: tuple[str, ...]) -> str:
    from g6.core.reliability_envelope import _door_mac

    return _door_mac("integrity", root, [list(item) for item in manifest], pin, list(patterns))


def verify_tree(root: str | os.PathLike[str], manifest: Mapping[str, str], *, expected_manifest_sha256: str = "",
                patterns: tuple[str, ...] = ("**/*.py",)) -> IntegrityResult:
    """Compare the files under ``root`` with ``manifest``; see the module docstring for what a match means."""
    problems = []
    present = bool(manifest)
    if not present:
        problems.append("no manifest: nothing to compare the files with")
    pinned = False
    if expected_manifest_sha256:
        pinned = manifest_sha256(manifest) == expected_manifest_sha256
        if not pinned:
            problems.append("the manifest's digest is not the pinned one")
    elif present:
        problems.append("the manifest is not pinned: a matching tree is a qualified draft")
    actual = build_manifest(root, patterns=patterns)
    missing = tuple(sorted(set(manifest) - set(actual)))
    modified = tuple(sorted(p for p in set(manifest) & set(actual) if manifest[p] != actual[p]))
    unexpected = tuple(sorted(set(actual) - set(manifest)))
    problems += [f"{len(x)} file(s) {what}" for x, what in ((missing, "missing"), (modified, "modified"),
                                                          (unexpected, "not in the manifest")) if x]
    matched = present and not (missing or modified or unexpected) and (pinned or not expected_manifest_sha256)
    resolved, listed = str(Path(root).resolve()), tuple(sorted(manifest.items()))
    return IntegrityResult(present, matched, pinned, missing, modified, unexpected, tuple(problems),
                           root=resolved, manifest=listed, expected_manifest_sha256=expected_manifest_sha256,
                           patterns=tuple(patterns),
                           seal=_seal(resolved, listed, expected_manifest_sha256, tuple(patterns)))


def verify_installed(manifest: Mapping[str, str], *, expected_manifest_sha256: str = "") -> IntegrityResult:
    """``verify_tree`` on the installed ``g6`` package: the code that is running."""
    import g6

    return verify_tree(Path(g6.__file__).resolve().parent, manifest, expected_manifest_sha256=expected_manifest_sha256)


__all__ = ["IntegrityResult", "build_manifest", "manifest_sha256", "manifest_text", "read_manifest", "verify_installed",
           "verify_tree", "write_manifest"]
