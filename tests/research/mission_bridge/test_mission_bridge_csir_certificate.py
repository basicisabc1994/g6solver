# --- S5: tamper evidence, scoped ---------------------------------------------------------------------------------------


def forged(body, edit):
    out = copy.deepcopy(body)
    edit(out)
    out["digest"] = C.digest_of(out)  # an unkeyed digest: a forger can always recompute it
    return out


def test_a_certificate_reverifies_against_its_bytes_and_its_mission():
    cert = issue(*verified_case())
    assert C.verify(cert.as_dict(), BYTES) == []
    assert C.verify(cert.as_dict(), BYTES, ir=make_ir(), standard=std()) == []
    assert C.verify(cert.as_dict(), BYTES + b"#") != []


def _p(body, name):
    return next(s for s in body["predicates"] if s["predicate"] == name)


def _forge_support(body):
    s = _p(body, "p-b")
    s.update(support=True, supported_by=["no-such-check"])
    body["gaps"] = [g for g in body["gaps"] if g[0] != "predicate:p-b"]
    body["state"] = "verified"


@pytest.mark.parametrize("edit", [
    _forge_support,                                                                      # support nothing backs
    lambda b: b.update(formal=[["p-a", "chk-a", "ef" * 32]]),                           # laundered onto the formal cert
    lambda b: b.update(receipts=[], rerun=[]),                                           # receipts dropped
    lambda b: _p(b, "p-a").update(support=1),                                            # not a boolean (1 == True)
    lambda b: b.update(violations=["self_verification"]),                               # a violation with no gap
    lambda b: b.update(rerun=[]),                                                        # re-run list changed
])
def test_an_offline_forgery_with_a_recomputed_digest_is_still_caught(edit):
    checks, receipts = verified_case()
    body = issue(checks, receipts[:1] if edit is _forge_support else receipts).as_dict()
    assert C.verify(body, BYTES) == []
    assert C.verify(forged(body, edit), BYTES) != []


def test_an_edit_without_a_recomputed_digest_is_caught_by_the_digest():
    body = issue(*verified_case()).as_dict()
    edited = copy.deepcopy(body)
    edited["producer"] = "someone else"  # internally consistent, so only the digest can tell
    assert C.verify(edited, BYTES) == ["the digest does not match the certificate's contents"]


def _qualified():
    checks, receipts = verified_case()
    return issue(checks, receipts[:1]).as_dict()


def _forge_support_with_rerun(b):
    _forge_support(b)
    b["rerun"].append(["no-such-check", "", "independent_executable"])


@pytest.mark.parametrize(("make", "edit", "says"), [
    (_qualified, lambda b: b.update(gaps=[]), "not named in the gaps"),
    (_qualified, _forge_support_with_rerun, "no pass receipt"),
    (lambda: issue(*verified_case()).as_dict(), lambda b: b["rerun"][0].__setitem__(2, "heuristic_review"), "cannot"),
])
def test_each_offline_consistency_rule_catches_its_own_forgery(make, edit, says):
    fake = forged(make(), edit)
    problems = C.verify(fake, BYTES)
    assert any(says in p for p in problems), problems


def test_a_blocked_certificate_that_drops_its_obligation_gaps_is_caught():
    raw = raw_ir()
    raw["nodes"][2]["source_operation"] = "gamma.write"
    raw["nodes"][2]["declared_effect"] = "local_write"
    body = issue(*verified_case(), ir=MissionIR.from_dict(raw)).as_dict()
    fake = forged(body, lambda b: b.update(gaps=[g for g in b["gaps"] if not g[0].startswith("obligation:")]))
    assert any("violations and the obligation gaps" in p for p in C.verify(fake, BYTES))


def test_a_mission_standard_with_the_same_predicates_but_another_hash_is_refused():
    other = SD.FrozenStandard("std-1", 1, PREDICATES, reason="another freeze of the same names")
    assert other.sha256 != std().sha256
    with pytest.raises(C.CertificateRefused, match="hash"):
        issue(*verified_case(), standard=other)


def test_given_only_the_mission_a_dropped_predicate_or_gate_is_still_caught():
    ir = make_ir(gate=True)
    body = issue(*verified_case(), ir=ir).as_dict()  # qualified only because the gate is undecided
    no_gate = forged(body, lambda b: b.update(gaps=[], state="verified"))
    # offline, verify decides again from what the certificate records (csir_certificate.v2), so the rewrite is caught
    assert C.verify(no_gate, BYTES) != []
    assert any("gate:approve" in p for p in C.verify(no_gate, BYTES, ir=ir))
    two = issue(*verified_case(), ir=make_ir()).as_dict()
    dropped = forged(two, lambda b: b.update(predicates=[_p(b, "p-a")], rerun=[r for r in b["rerun"] if r[0] == "chk-a"]))
    assert C.verify(dropped, BYTES) != []
    assert any("not the mission's" in p for p in C.verify(dropped, BYTES, ir=make_ir()))


@pytest.mark.parametrize("edit", [
    lambda b: (b.update(predicates=[_p(b, "p-a")], gaps=[], state="verified")),       # an unverified predicate dropped
    lambda b: b.update(gaps=[g for g in b["gaps"] if not g[0].startswith("gate:")], state="verified"),  # gate gap dropped
    lambda b: b.update(standard_sha="00" * 32),
    lambda b: b.update(mission_sha="00" * 32),
])
def test_given_the_mission_and_standard_a_verifier_also_catches_what_offline_cannot(edit):
    ir = make_ir(gate=True)
    checks, receipts = verified_case()
    body = issue(checks, receipts[:1], ir=ir).as_dict()
    fake = forged(body, edit)
    assert C.verify(fake, BYTES, ir=ir, standard=std()) != []


def test_a_state_that_disagrees_with_its_own_statements_fails_even_with_a_recomputed_digest():
    body = issue(verified_case()[0], []).as_dict()
    fake = forged(body, lambda b: b.update(state="verified"))
    assert any("state" in p for p in C.verify(fake, BYTES))


