@settings(max_examples=200, suppress_health_check=[HealthCheck.too_slow])
@given(near_verified(), st.sampled_from(SV.EXISTENCE))
def test_a_solvability_belief_never_changes_the_state(case, existence):
    checks, receipts = case
    plain = issue(checks, receipts)
    belief = SV.Solvability(existence=existence, basis="" if existence == "unknown" else "stated basis")
    believed = issue(checks, receipts, solvability=belief)
    assert believed.state == plain.state and believed.gaps == plain.gaps
    assert believed.as_dict()["solvability"]["existence"] == existence
