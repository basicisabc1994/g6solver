AUTHORS = ("agent:customer", "g6:constructor", PRODUCER)


@st.composite
def near_verified(draw):
    """A verified case with zero to two random changes: verified often enough that S1 is exercised, not vacuous."""
    checks, receipts = verified_case()
    checks, receipts = list(checks), list(receipts)
    for _ in range(draw(st.integers(min_value=0, max_value=2))):
        i = draw(st.integers(0, len(checks) - 1))
        c = checks[i]
        what = draw(st.sampled_from(("kind", "author", "frozen", "control", "receipt", "extra_fail", "extra_pass")))
        if what == "kind":
            checks[i] = good_check(c.check_id, c.predicates, kind=draw(st.sampled_from(C.EVIDENCE_KINDS)),
                                   certificate="ef" * 32 if draw(st.booleans()) else "")
        elif what == "author":
            checks[i] = good_check(c.check_id, c.predicates, author=draw(st.sampled_from(AUTHORS)))
        elif what == "frozen":
            checks[i] = good_check(c.check_id, c.predicates, frozen_seq=draw(st.integers(0, 15)))
        elif what == "control":
            checks[i] = good_check(c.check_id, c.predicates, ctl={
                "generated_by": draw(st.sampled_from((C.G6, "agent:customer"))), "seq": draw(st.integers(0, 30)),
                "killed": draw(st.booleans()), "check_sha": draw(st.sampled_from((c.check_sha, "00" * 32)))})
        elif what == "receipt":
            r = receipts[i]
            receipts[i] = C.Receipt(r.receipt_id, r.check_id, draw(st.sampled_from((r.check_sha, "00" * 32))),
                                    draw(st.sampled_from((ART_SHA, OTHER_SHA))), draw(st.sampled_from(C.RESULTS)),
                                    draw(st.integers(0, 40)))
        else:
            new = good_check(f"chk-x{len(checks)}", [draw(st.sampled_from(PREDICATES))],
                             author=draw(st.sampled_from(AUTHORS)), ctl={"killed": draw(st.booleans())})
            checks.append(new)
            receipts.append(receipt(new, "fail" if what == "extra_fail" else "pass", seq=draw(st.integers(0, 40))))
    return checks, receipts


def _grounded_pass(p, checks, receipts, art):
    by_id = {c.check_id: c for c in checks}
    for r in receipts:
        c = by_id[r.check_id]
        controls = [k for k in c.controls if k.predicate == p and k.check_sha == c.check_sha and k.generated_by == C.G6
                    and k.killed and c.frozen_seq <= k.seq < r.seq]
        if (r.result == "pass" and r.artifact_sha == art.sha256 and r.check_sha == c.check_sha and p in c.predicates
                and c.kind in C.A4_KINDS and c.author != art.producer and c.frozen_seq < art.seq and r.seq >= art.seq
                and controls and (c.kind != "formal_checked" or c.certificate)):
            return True
    return False


@settings(max_examples=400, suppress_health_check=[HealthCheck.too_slow])
@given(near_verified())
def test_s1_s2_verified_means_every_predicate_has_a_grounded_pass_and_every_other_predicate_is_named(case):
    checks, receipts = case
    art = artifact()
    cert = issue(checks, receipts, art=art)
    if cert.state == "verified":
        assert all(_grounded_pass(p, checks, receipts, art) for p in PREDICATES)
        assert not any(s.refute for s in cert.predicates)
    for p in PREDICATES:
        if p not in cert.verified_predicates:
            assert any(subject == f"predicate:{p}" for subject, _ in cert.gaps), (p, cert.gaps)
    assert C.verify(cert.as_dict(), BYTES, ir=make_ir(), standard=std()) == []


