"""The certificate issuer (Runtime Validator Constructor R1, 2026-10-14): the one place a mission's state is decided.

``issue`` judges the mission itself against the catalogue it is given (it never accepts a judgement from outside) and is
bound to the frozen standard: the mission's standard hash must be that standard's hash, with the same predicates. Each
predicate carries a Belnap value (support, refute) built only from receipts on the exact artifact bytes. ``verified`` needs
every predicate supported, none refuted and no unresolved caveat, by a check that meets, for that predicate, the A4 grounding
rule the founder approved on 2026-10-14 (D2):
- evidence kind ``independent_executable`` or ``formal_checked`` (a formal check also names its certificate digest);
- its author is not the artifact's producer;
- it was frozen before the artifact existed;
- a negative control for *that predicate* and *that check's code*, generated by G6, was killed, recorded at or after the
  freeze and before the receipt it backs;
- the receipt was taken after the artifact existed, names the check's frozen hash and the artifact's hash.

Guarantees pinned here over generated inputs, not over a dataset:
- S1 soundness: a verified certificate has, for every predicate, a receipt meeting every condition above, and no refutation;
- S2 no silent gaps: every predicate that is not verified is named in the gaps;
- non-monotone: one failing admitted check turns a verified mission into blocked-escalated;
- S5 tamper evidence, scoped honestly: offline, the certificate must match its artifact bytes and be internally consistent
  (every support backed by a pass receipt on those bytes, the formal certificate only from verified formal support, the
  re-run list equal to the support); given the mission and the standard, a verifier also catches a dropped predicate, a
  dropped gate gap and a changed mission or standard hash;
- a solvability belief is carried but never changes the state.
"""
from __future__ import annotations

import copy
import hashlib

import pytest
from hypothesis import HealthCheck, given, settings
