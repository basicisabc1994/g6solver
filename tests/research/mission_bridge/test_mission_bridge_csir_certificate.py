BYTES = b"def handler(event):\n    return 'ok'\n"
ART_SHA = hashlib.sha256(BYTES).hexdigest()
OTHER_SHA = hashlib.sha256(b"something else").hexdigest()
PRODUCER = "local:gpt-oss:20b"
PREDICATES = ("p-a", "p-b")
CATALOG = {
    "alpha.ask": OpFact(effect="read", authority="A1"),
    "gamma.write": OpFact(effect="local_write", authority="A1"),
    "delta.check": OpFact(effect="read", authority="A4"),
}


@pytest.fixture(autouse=True)
def _on(monkeypatch):
    monkeypatch.setenv(FLAG, "1")


def std(predicates=PREDICATES):
    return SD.FrozenStandard.first("std-1", predicates)


def _node(node_id, op, requires, provides, **over):
    body = {"id": node_id, "role": node_id, "source_operation": op, "declared_effect": CATALOG[op].effect,
            "requires": requires, "provides": provides, "budget_cents": 10}
    body.update(over)
    return body


def raw_ir(gate=False, standard=None, predicates=PREDICATES):
    standard = standard or std()
    nodes = [
        _node("scope", "alpha.ask", {"question": "text"}, {"scope": "text"}),
        _node("draft", "gamma.write", {"scope": "text"}, {"draft": "file"}),
        _node("check", "delta.check", {"draft": "file"}, {"verdict": "check_result"}, verifies="draft"),
    ]
    if gate:
        nodes.append({"id": "approve", "role": "approve", "source_operation": "", "declared_effect": "read",
                      "requires": {"verdict": "check_result"}, "provides": {"approved": "decision"}, "gate": True})
    return {"mission_id": "m-1", "domain": "synthetic", "high_stakes": False, "inputs": {"question": "text"},
            "standard": {"standard_id": "std-1", "standard_sha256": standard.sha256, "predicates": list(predicates)},
            "nodes": nodes, "budget_cents": 100}


def make_ir(**kw):
    return MissionIR.from_dict(raw_ir(**kw))


def artifact(sha=ART_SHA, seq=10):
    return C.Artifact(sha256=sha, producer=PRODUCER, seq=seq)


def check_sha(check_id):
    return hashlib.sha256(check_id.encode()).hexdigest()


def good_check(check_id, predicates, ctl=None, controls=None, **over):
    sha = over.get("check_sha", check_sha(check_id))
    if controls is None:
        controls = tuple(C.Control(**{"control_id": f"{check_id}-{p}", "check_sha": sha, "predicate": p,
                                      "generated_by": C.G6, "seq": 2, "killed": True, **(ctl or {})})
                         for p in predicates)
    body = {"check_id": check_id, "predicates": tuple(predicates), "author": "agent:customer",
            "kind": "independent_executable", "check_sha": sha, "frozen_seq": 1, "controls": tuple(controls),
            "positive_seq": 2}
    body.update(over)
    return C.Check(**body)


def receipt(check, result="pass", seq=20, **over):
    body = {"receipt_id": f"r-{check.check_id}-{seq}-{result}", "check_id": check.check_id, "check_sha": check.check_sha,
            "artifact_sha": ART_SHA, "result": result, "seq": seq}
    body.update(over)
    return C.Receipt(**body)


def observed(checks, receipts):
    """The ledger G6's runner would have written: every control and receipt given, once per id (EVIDENCE-01)."""
    ledger = ChainLedger()
    kept = {("control", c.control_id): c for check in checks for c in reversed(check.controls)}
    kept.update({("receipt", r.receipt_id): r for r in reversed(receipts)})
    record(ledger, *kept.values())
    return ledger


def issue(checks, receipts, *, ir=None, standard=None, art=None, decisions=(), solvability=None, catalogue=None):
    # The rule tests below judge records G6 wrote; tests/evidence covers records it did not.
    return C.issue(ir or make_ir(), CATALOG if catalogue is None else catalogue, standard or std(), art or artifact(),
                   checks, receipts, decisions=decisions, solvability=solvability, ledger=observed(checks, receipts))


def verified_case():
    a, b = good_check("chk-a", ["p-a"]), good_check("chk-b", ["p-b"])
    return [a, b], [receipt(a), receipt(b)]


def gaps_for(cert, predicate):
    return " ".join(why for subject, why in cert.gaps if subject == f"predicate:{predicate}")


# --- binding: the issuer judges what it certifies ---------------------------------------------------------------------


def test_every_predicate_supported_by_a_grounded_check_is_verified():
    cert = issue(*verified_case())
    assert cert.state == "verified"
    assert cert.verified_predicates == PREDICATES and cert.gaps == ()
    assert cert.catalogue_sha == C.catalogue_sha(CATALOG) and cert.standard_sha == std().sha256


def test_the_issuer_judges_the_mission_itself_so_a_permissive_catalogue_is_what_it_records():
    raw = raw_ir()
    raw["nodes"][2]["source_operation"] = "gamma.write"  # the writer checks itself (A5)
    raw["nodes"][2]["declared_effect"] = "local_write"
    ir = MissionIR.from_dict(raw)
    cert = issue(*verified_case(), ir=ir)
    assert cert.state == "blocked-escalated" and "self_verification" in cert.violations
    assert any(subject == "obligation:A5" for subject, _ in cert.gaps)


def test_issue_takes_no_judgement_from_outside():
    import inspect
    assert "judgement" not in inspect.signature(C.issue).parameters


def test_a_mission_whose_standard_hash_names_a_wider_standard_than_it_lists_is_refused():
    full = std(("p-a", "p-b"))
    half = MissionIR.from_dict(raw_ir(standard=full, predicates=("p-a",)))
    a = good_check("chk-a", ["p-a"])
    with pytest.raises(C.CertificateRefused, match="standard"):
        issue([a], [receipt(a)], ir=half, standard=full)


def test_a_mission_under_another_standard_is_refused():
    with pytest.raises(C.CertificateRefused, match="standard"):
        issue(*verified_case(), standard=std(("p-a", "p-b", "p-c")))


# --- the grounding rule, per predicate --------------------------------------------------------------------------------


@pytest.mark.parametrize(("change", "reason"), [
    ({"kind": "partial_falsifier"}, "evidence_kind"),
    ({"kind": "heuristic_review"}, "evidence_kind"),
    ({"author": PRODUCER}, "self_authored"),
    ({"frozen_seq": 10}, "frozen_after_artifact"),
    ({"controls": ()}, "no_negative_control"),
    ({"ctl": {"generated_by": "agent:customer"}}, "control_not_generated_by_g6"),
    ({"ctl": {"killed": False}}, "control_not_killed"),
    ({"ctl": {"check_sha": "00" * 32}}, "control_for_other_code"),
    ({"ctl": {"seq": 0}, "frozen_seq": 1}, "control_before_freeze"),
    ({"kind": "formal_checked"}, "formal_without_certificate"),
])
def test_a_check_that_misses_any_grounding_condition_does_not_support(change, reason):
    a = good_check("chk-a", ["p-a"], **change)
    b = good_check("chk-b", ["p-b"])
    cert = issue([a, b], [receipt(a), receipt(b)])
    assert cert.state == "qualified-draft"
    assert reason in C.grounding(a, artifact(), "p-a")
    assert reason in gaps_for(cert, "p-a")


def test_a_check_covering_two_predicates_needs_a_control_for_each():
    sha = check_sha("chk-ab")
    only_a = (C.Control("c-a", sha, "p-a", C.G6, 2, True),)
    ab = good_check("chk-ab", ["p-a", "p-b"], controls=only_a)
    cert = issue([ab], [receipt(ab)])
    assert cert.verified_predicates == ("p-a",) and cert.state == "qualified-draft"
    assert "no_negative_control" in gaps_for(cert, "p-b")
    both = good_check("chk-ab", ["p-a", "p-b"])
    assert issue([both], [receipt(both)]).state == "verified"


def test_a_formal_check_with_a_certificate_digest_supports_and_appears_on_the_formal_certificate():
    a = good_check("chk-a", ["p-a"], kind="formal_checked", certificate="ef" * 32)
    b = good_check("chk-b", ["p-b"])
    cert = issue([a, b], [receipt(a), receipt(b)])
    assert cert.state == "verified"
    assert cert.formal == (("p-a", "chk-a", "ef" * 32),)


def test_executable_evidence_is_never_laundered_onto_the_formal_certificate():
    assert issue(*verified_case()).formal == ()


def test_a_control_recorded_after_the_receipt_does_not_back_it():
    a = good_check("chk-a", ["p-a"], ctl={"seq": 30})
    b = good_check("chk-b", ["p-b"])
    cert = issue([a, b], [receipt(a, seq=20), receipt(b)])
    assert cert.state == "qualified-draft" and "control_after_receipt" in gaps_for(cert, "p-a")


def test_a_receipt_taken_before_the_artifact_existed_counts_for_nothing():
    a, b = good_check("chk-a", ["p-a"]), good_check("chk-b", ["p-b"])
    cert = issue([a, b], [receipt(a, seq=5), receipt(b)])
    assert cert.state == "qualified-draft" and "receipt_before_artifact" in gaps_for(cert, "p-a")


def test_negative_ledger_positions_are_refused():
    with pytest.raises(C.CertificateRefused):
        C.Artifact(ART_SHA, PRODUCER, -5)
    with pytest.raises(C.CertificateRefused):
        good_check("chk-a", ["p-a"], frozen_seq=-1)
    with pytest.raises(C.CertificateRefused):
        receipt(good_check("chk-a", ["p-a"]), seq=-1)
    with pytest.raises(C.CertificateRefused):
        C.Control("c", check_sha("x"), "p-a", C.G6, -1, True)


def test_a_receipt_on_other_bytes_or_from_a_changed_check_counts_for_nothing():
    a, b = good_check("chk-a", ["p-a"]), good_check("chk-b", ["p-b"])
    stale = issue([a, b], [receipt(a, artifact_sha=OTHER_SHA), receipt(b)])
    assert stale.state == "qualified-draft" and "receipt_for_other_bytes" in gaps_for(stale, "p-a")
    changed = issue([a, b], [receipt(a, check_sha="00" * 32), receipt(b)])
    assert changed.state == "qualified-draft" and "check_changed_after_freeze" in gaps_for(changed, "p-a")


# --- refutation, caveats, gates ---------------------------------------------------------------------------------------


def test_a_failing_admitted_check_refutes_and_blocks_even_beside_support():
    checks, receipts = verified_case()
    second = good_check("chk-a2", ["p-a"], author="g6:constructor")
    cert = issue([*checks, second], [*receipts, receipt(second, "fail")])
    assert cert.state == "blocked-escalated"
    statement = next(s for s in cert.predicates if s.predicate == "p-a")
    assert (statement.support, statement.refute) == (True, True)  # Belnap conflict, never averaged away


@pytest.mark.parametrize("ctl", [{"killed": False}, {"seq": 30}, {"check_sha": "00" * 32}])
def test_a_failure_from_a_check_that_had_not_shown_it_can_fail_is_a_caveat_not_a_refutation(ctl):
    checks, receipts = verified_case()
    weak = good_check("chk-weak", ["p-a"], author="g6:constructor", ctl=ctl)
    cert = issue([*checks, weak], [*receipts, receipt(weak, "fail", seq=20)])
    assert cert.state == "qualified-draft"
    assert not any(s.refute for s in cert.predicates)
    assert "advisory_check_failed:chk-weak" in gaps_for(cert, "p-a")


@pytest.mark.parametrize("positive", [None, 30], ids=["never_passed_a_reference", "passed_one_only_after_the_receipt"])
def test_a_failure_from_a_check_that_has_not_passed_a_known_good_reference_is_a_caveat_not_a_refutation(positive):
    """An always-failing check kills every control; only a pass on a known-good reference shows its failures mean
    something, so without one a failure cannot refute correct work (R2 review finding 5)."""
    checks, receipts = verified_case()
    blunt = good_check("chk-blunt", ["p-a"], author="g6:constructor", positive_seq=positive)
    cert = issue([*checks, blunt], [*receipts, receipt(blunt, "fail")])
    assert cert.state == "qualified-draft" and not any(s.refute for s in cert.predicates)
    assert "advisory_check_failed:chk-blunt" in gaps_for(cert, "p-a")


