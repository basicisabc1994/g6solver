"""A stand-in for Graphviz's dot, owned by G6's tests: started through the same child-process path as the real one.

It answers ``-V`` as dot does (on stderr), and ``-T<svg|png> -o <file> <source>`` by reading the DOT it is given (a
small reader of the subset the tests write), laying the nodes out in a column and writing an SVG shaped like dot's
(its DOCTYPE line, a background polygon, a ``<g class="node">`` with a ``<title>`` per node and a ``<g class="edge">``
per edge) or a PNG of that layout. A syntax error is reported on stderr as dot reports it, with exit code 1.

``behaviour.json`` beside it says how to misbehave: ``mode`` is ``normal``, ``blank`` (nothing drawn), ``drop_node``
(the last node not drawn), ``rewire`` (the same nodes and as many edges, joined differently: ``a->b, b->c`` drawn as
``a->c, c->b``), ``garbage`` (bytes that are not the format), ``hang`` (never finishes), ``crash`` (exit 3),
``no_output`` (exit 0, no file) or ``noisy`` (normal, with a warning on stderr). Each start is logged to
``calls.jsonl`` beside it: the arguments, the environment and the working folder.
"""
from __future__ import annotations

import json
import os
import re
import struct
import sys
import time
import zlib
from pathlib import Path
from xml.sax.saxutils import escape

HERE = Path(__file__).resolve().parent
TOKEN = re.compile(r'\s+|^#[^\n]*|//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|->|--|[{}\[\];,=:+]|[A-Za-z_0-9.\x80-\uffff]+|(.)',
                   re.S | re.M)


def behaviour() -> dict:
    path = HERE / "behaviour.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {"mode": "normal"}


def log(args: list[str]) -> None:
    with open(HERE / "calls.jsonl", "a", encoding="utf-8") as f:
        f.write(json.dumps({"argv": args, "env": dict(os.environ), "cwd": os.getcwd()}) + "\n")


def unquote(token: str) -> str:
    return token[1:-1].replace('\\"', '"') if token.startswith('"') else token


def parse(source: str) -> tuple[list[tuple[str, str]], list[tuple[str, str]]]:
    tokens = []
    for m in TOKEN.finditer(source):
        if m.group(1) is not None:
            raise SyntaxError(m.group(1))
        text = m.group(0)
        if not text.isspace() and not text.startswith(("//", "/*", "#")) and text != "+":
            tokens.append(text)
    if tokens.count("{") != tokens.count("}") or "{" not in tokens:
        raise SyntaxError(tokens[-1] if tokens else "")
    body = tokens[tokens.index("{") + 1:len(tokens) - 1 - tokens[::-1].index("}")]
    nodes: dict[str, str] = {}
    edges: list[tuple[str, str]] = []
    i = 0
    while i < len(body):
        tok = body[i]
        if tok in (";", ",", "{", "}"):
            i += 1
            continue
        if tok in ("graph", "node", "edge") and i + 1 < len(body) and body[i + 1] == "[":
            i = body.index("]", i) + 1
            continue
        if i + 1 < len(body) and body[i + 1] == "=":
            i += 3
            continue
        chain = [unquote(tok)]
        i += 1
        while i + 1 < len(body) and body[i] == ":":  # a port: a:p or a:p:n
            i += 2
        while i + 1 < len(body) and body[i] in ("->", "--"):
            chain.append(unquote(body[i + 1]))
            i += 2
            while i + 1 < len(body) and body[i] == ":":
                i += 2
        attrs: dict[str, str] = {}
        if i < len(body) and body[i] == "[":
            end = body.index("]", i)
            parts = body[i + 1:end]
            for k in range(len(parts) - 2):
                if parts[k + 1] == "=":
                    attrs[unquote(parts[k])] = unquote(parts[k + 2])
            i = end + 1
        for name in chain:
            nodes.setdefault(name, name)
        if len(chain) == 1 and "label" in attrs:
            nodes[chain[0]] = attrs["label"]
        edges += list(zip(chain, chain[1:]))
    return list(nodes.items()), edges


def svg(nodes: list[tuple[str, str]], edges: list[tuple[str, str]], arrow: str) -> bytes:
    width, height = 120, 72 * max(1, len(nodes)) + 8
    out = ['<?xml version="1.0" encoding="UTF-8" standalone="no"?>',
           '<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN"',
           ' "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">',
           "<!-- Generated by the G6 tests' stand-in for dot -->",
           f'<svg width="{width}pt" height="{height}pt"',
           f' viewBox="0.00 0.00 {width}.00 {height}.00" xmlns="http://www.w3.org/2000/svg" '
           'xmlns:xlink="http://www.w3.org/1999/xlink">',
           f'<g id="graph0" class="graph" transform="scale(1 1) rotate(0) translate(4 {height - 4})">',
           "<title>G</title>",
           f'<polygon fill="white" stroke="none" points="-4,4 -4,{4 - height} {width - 4},{4 - height} '
           f'{width - 4},4 -4,4"/>']
    where = {}
    for k, (name, label) in enumerate(nodes, 1):
        y = -(18 + 72 * (k - 1)) - 8
        where[name] = y
        out += [f'<g id="node{k}" class="node">', f"<title>{escape(name)}</title>",
                f'<ellipse fill="none" stroke="black" cx="56" cy="{y}" rx="27" ry="18"/>',
                f'<text text-anchor="middle" x="56" y="{y + 4}" font-family="Times,serif" font-size="14.00">'
                f"{escape(label)}</text>", "</g>"]
    for k, (a, b) in enumerate(edges, 1):
        out += [f'<g id="edge{k}" class="edge">', f"<title>{escape(a)}{escape(arrow)}{escape(b)}</title>",
                f'<path fill="none" stroke="black" d="M56,{where[a] - 18}C56,{where[a] - 30} 56,{where[b] + 30} '
                f'56,{where[b] + 18}"/>', "</g>"]
    return ("\n".join([*out, "</g>", "</svg>"]) + "\n").encode("utf-8")


def png(nodes: list[tuple[str, str]]) -> bytes:
    width, height = round(120 * 96 / 72), round((72 * max(1, len(nodes)) + 8) * 96 / 72)
    rows = []
    for y in range(height):
        row = bytearray(b"\xff" * width * 3)
        for k in range(len(nodes)):
            centre = round((26 + 72 * k) * 96 / 72)
            if abs(y - centre) < 20:
                row[3 * 50:3 * 100] = b"\x00" * 150
        rows.append(b"\x00" + bytes(row))

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(b"".join(rows))) + chunk(b"IEND", b""))


def main(args: list[str]) -> int:
    log(args)
    if args == ["-V"]:
        print("dot - graphviz version 0.0.0-stand-in (g6 tests)", file=sys.stderr)
        return 0
    mode = behaviour().get("mode", "normal")
    fmt = next(a[2:] for a in args if a.startswith("-T"))
    target, source = args[args.index("-o") + 1], args[-1]
    if mode == "hang":
        time.sleep(600)
    if mode == "crash":
        print("Error: the stand-in ran out of something", file=sys.stderr)
        return 3
    text = Path(source).read_text(encoding="utf-8")
    try:
        nodes, edges = parse(text)
    except SyntaxError as exc:
        print(f"Error: {source}: syntax error in line 1 near '{exc}'", file=sys.stderr)
        return 1
    if mode == "no_output":
        return 0
    if mode == "blank":
        nodes, edges = [], []
    if mode == "drop_node":
        nodes = nodes[:-1]
        edges = [e for e in edges if all(end in dict(nodes) for end in e)]
    if mode == "rewire" and len(edges) >= 2:
        edges = [(edges[0][0], edges[-1][1]), (edges[-1][1], edges[0][1]), *edges[1:-1]]
    arrow = "->" if text.lstrip().startswith(("digraph", "strict digraph")) else "--"
    data = b"not a picture" if mode == "garbage" else svg(nodes, edges, arrow) if fmt == "svg" else png(nodes)
    Path(target).write_bytes(data)
    if mode == "noisy":
        print("Warning: the stand-in has something to say", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
