# --- the inventory: one status, decided once, from the kept patch -------------------------------------------------------------
LOOPS = {"reviews_until_clean", "review_once", "reviews_with_bug_test", "repair_loop"}


def _dict_keys(fn: ast.AST) -> set[str]:
    return {k.value for ret in ast.walk(fn) if isinstance(ret, ast.Return) and isinstance(ret.value, ast.Dict)
            for k in ret.value.keys if isinstance(k, ast.Constant)}


def test_every_loop_returns_what_it_found_and_the_status_is_decided_once_from_the_kept_patch_after_the_final_mirror():
    source = (ROOT / "validation" / "worked_examples" / "run.py").read_text("utf-8")
    module = ast.parse(source)
    fns = {n.name: n for n in ast.walk(module) if isinstance(n, ast.FunctionDef)}
    for name in LOOPS:                     # every return of a loop gives what it found, and none a status
        returns = [r for r in ast.walk(fns[name]) if isinstance(r, ast.Return) and isinstance(r.value, ast.Dict)]
        assert returns and all("found" in _dict_keys(ast.Module(body=[r], type_ignores=[])) for r in returns), name
        assert "status" not in _dict_keys(fns[name]), f"{name} decides a status itself"
    calls = [n for n in ast.walk(module) if isinstance(n, ast.Call) and getattr(n.func, "id", "") == "loop_status"]
    assert len(calls) == 1, f"the one rule is applied at lines {[c.lineno for c in calls]}: once, in _run_task, only"
    call = calls[0]
    run_task = fns["_run_task"]
    assert run_task.lineno <= call.lineno <= run_task.end_lineno, "the status is decided outside _run_task"
    assert ast.unparse(call) == ("loop_status(record['repairs']['found'], record['final_patch_bytes'] "
                                 "if record['final_patch_read'] else None)"), ast.unparse(call)

    def last_line(name: str) -> int:
        return max(n.lineno for n in ast.walk(run_task) if isinstance(n, ast.Call)
                   and (getattr(n.func, "attr", None) or getattr(n.func, "id", None)) == name)
    kept_at = last_line("keep_final")
    assert last_line("mirror") < kept_at < call.lineno, "the status is not measured from the patch kept after the final mirror"
    size_at = next(n.lineno for n in ast.walk(run_task) if isinstance(n, ast.Assign) and any(
        isinstance(t, ast.Subscript) and getattr(t.slice, "value", None) == "final_patch_bytes" for t in t_list(n)))
    assert kept_at <= size_at < call.lineno
    assert not hasattr(we, "patch_bytes") and not hasattr(we, "PATCH_BYTES"), "a second read of the patch's size"
    clean_words = [n.lineno for n in ast.walk(module) if isinstance(n, ast.Constant) and n.value == CLEAN]
    assert len(clean_words) == 1, f"the clean word is written at lines {clean_words}: one fact, one place"
    assert compare.CLEAN == we.LOOP_CLEAN


def t_list(node: ast.Assign) -> list[ast.AST]:
    return list(node.targets)
