"""The replay cohort's defect 2 (PLAN.md, 2026-11-06): a review called an empty patch clean (K3 pilot, pygments-3158 repeat 1:
first patch, rule patch and final patch all empty; review 1 said "none"; the loop's status was "no_counterexample_in_domain").

An empty patch is never clean: every review loop's status is decided by one rule (``run.loop_status``) from what the loop found
and the size of the patch the run keeps. A kept patch with no change is "no_patch"; a loop is clean only over a kept patch known
to hold a change; a size that was not read is never clean.

Replay cohort, repair 3 (review 3's finding 2; class ``check_then_act_race``): the status was measured in the container after the
reviewer's test had run, a file that test wrote included, and the final mirror then removed that file without the status being
measured again, so an author who changed nothing ended clean. The status is now measured once, in ``_run_task``, from the one read
that keeps the patch (``keep_final``, after the final mirror); a loop returns only what it found (``found``) and measures nothing.
Fakes only: no docker, no model."""
