def test_a_kept_patch_that_was_not_read_is_never_clean(monkeypatch, tmp_path):
    def unread(self, ctr, script, *a, **kw):                  # the final capture's add fails; every other capture passes
        if f"{we.WE}/final.patch" in script:
            return helpers.ok(f"{we.STEP} index=0\n{we.STEP} cd=0\n{we.STEP} read-tree=0\n{we.STEP} add=128\n"
                              f"{we.STEP} cleanup=0\n".encode(), code=128)
        return plain(self, ctr, script, *a, **kw)

    plain = tree.BoxDocker.sh
    monkeypatch.setattr(tree.BoxDocker, "sh", unread)
    got = _reviewed(monkeypatch, tmp_path, [("s1", [("write", "src/mod.py", b"def f():\n    return 1\n")])], None)
    assert got.record["final_patch_read"] is False and got.record["final_patch_why"] == "the capture's step add exited 128"
    assert got.record["repairs"]["status"] == "inconclusive", got.record["repairs"]


