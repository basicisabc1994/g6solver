class StillDocker:
    """A container whose tree never moves, which keeps every script it is sent."""

    def __init__(self):
        self.scripts = []

    def sh(self, agent, script, *a, **kw):
        self.scripts.append(script)
        return SimpleNamespace(returncode=0, stdout=b"tree 0", stderr=b"")


