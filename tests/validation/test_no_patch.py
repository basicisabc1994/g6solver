# --- review 3's finding 2: the status is the kept patch's, measured after the final mirror -------------------------------------
TOY = we.Task(id="toy-1", project="review/toy", full_name="review/toy", licence="MIT", pr=1, issue=1, merge_commit="1" * 40,
              parent="0" * 40, merged_at="", test_modules=("tests/test_mod.py",), install=())


def _reviewed(monkeypatch, tmp_path, sessions, writes: bytes | None):
    """One host K2 run of a toy bug whose reviewer's test, when it runs, writes ``writes`` (None: nothing) into the container's
    ``review-output.txt``, then passes, so the loop finds nothing open."""
    monkeypatch.setattr(we, "load_tasks", lambda: [TOY])

    def review(n):
        def run_review_test(*args, **kwargs):
            if writes is not None:
                (tmp_path / "container" / "toy" / "review-output.txt").write_bytes(writes)
            return we.ProbeRun(0, {"test_critic.py::test_generated": "passed"}, {}, "")
        monkeypatch.setattr(we, "run_set", run_review_test)
        return {"verdict": "defect", "rule": "r", "why": "w", "test": "def test_generated(): pass", "seconds": 0.0}

    return tree.run_with(monkeypatch, tmp_path, "K2", sessions, commands={}, review=review)


def test_review_3_finding_2_a_file_the_reviewers_test_wrote_and_the_final_mirror_removed_never_makes_an_empty_patch_clean(
        monkeypatch, tmp_path):
    got = _reviewed(monkeypatch, tmp_path, [("s1", [])], b"generated by the review test\n")
    assert got.record["status"] == "finished", got.record.get("error")
    assert got.record["final_patch_read"] is True
    assert (got.folder / "final.patch").read_bytes() == b""
    assert got.record["repairs"]["status"] == we.NO_PATCH, (
        "the loop certified the review test's generated file, then kept an empty author patch", got.record["repairs"])
    assert got.record["repairs"]["found"] == CLEAN                       # what the loop found stands beside the status


def test_a_file_the_reviewers_test_wrote_where_the_author_wrote_is_kept_as_the_author_left_it_and_the_status_is_measured_on_it(
        monkeypatch, tmp_path):
    authored = b"by the author\n"
    got = _reviewed(monkeypatch, tmp_path, [("s1", [("write", "review-output.txt", authored)])], b"generated by the review test\n")
    assert got.record["status"] == "finished", got.record.get("error")
    final = (got.folder / "final.patch").read_bytes()
    assert final == tree.entry("review-output.txt", authored), final          # the final mirror kept the author's file
    assert got.record["repairs"]["status"] == CLEAN and got.record["final_patch_bytes"] == len(final)


def test_an_empty_kept_patch_that_no_review_touched_is_no_patch(monkeypatch, tmp_path):
    got = _reviewed(monkeypatch, tmp_path, [("s1", [])], None)
