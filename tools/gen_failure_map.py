"""Regenerate the failure-mode map from the installed code (never edit the outputs by hand).

    python tools/gen_failure_map.py           # write catalog/failure_modes.json and site/docs/failure-modes.md
    python tools/gen_failure_map.py --check   # exit 1 if either is out of date (used by the test suite)

The map is the Swiss cheese picture of the framework design (section 4): every failure mode in
``g6.core.failure_modes``, the components that guard against it today (their own ``__g6_mitigates__``), the ones whose
use can cause it (``__g6_introduces__``), and the packages planned to guard it (``data/failure_modes/<family>.json``).
A planned package is never listed as guarding: only a registered component's own declaration puts it there, and a
component built in a vetted area whose certificate is not current (``g6.core.vetting``) is listed as awaiting its
certificate.

The JSON keeps every planned package. The page names them only while the website's one switch is on
(``SHOW_PLANNED`` in ``web/pages/extensions.py``, owner, 2026-10-23: the site shows only what is in the library).
"""
from __future__ import annotations

import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JSON_OUT = ROOT / "catalog" / "failure_modes.json"
MD_OUT = ROOT / "site" / "docs" / "failure-modes.md"
SWITCH = ROOT / "web" / "pages" / "extensions.py"


def show_planned() -> bool:
    """The website's switch, read from its source as a literal (the site's package is not imported here)."""
    for node in ast.parse(SWITCH.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and [getattr(t, "id", None) for t in node.targets] == ["SHOW_PLANNED"]:
            value = ast.literal_eval(node.value)
            if isinstance(value, bool):
                return value
    raise SystemExit(f"{SWITCH.relative_to(ROOT)}: no SHOW_PLANNED = True or False")


def collect() -> list[dict]:
    from g6.core import vetting
    from g6.core.failure_modes import FailureModeRegistry
    from g6.core.registry import get_registry

    reg = get_registry()
    guards: dict[str, list[str]] = {}
    causes: dict[str, list[str]] = {}
    waiting: dict[str, list[str]] = {}
    for name in reg.names():
        mod = reg.get_module(name)
        held = vetting.awaiting_review(reg.refs[name].module.split(":", 1)[0])  # built, its certificate not current
        for code in getattr(mod, "__g6_mitigates__", ()):
            (waiting if held else guards).setdefault(code, []).append(name)
        for code in getattr(mod, "__g6_introduces__", ()):
            causes.setdefault(code, []).append(name)
    component = {reg.refs[name].module.split(":", 1)[0]: name for name in reg.names()}
    planned: dict[str, list[str]] = {}
    for package, codes in FailureModeRegistry.planned().items():
        for code in codes:
            if component.get(package) not in guards.get(code, []):
                planned.setdefault(code, []).append(package)
    return [{
        "code": str(record.code),
        "title": record.title or record.description,
        "description": record.description,
        "severity": record.severity,
        "requires_human_review": record.requires_human_review,
        "aliases": list(record.aliases),
        "guarded_by": sorted(guards.get(str(record.code), [])),
        "introduced_by": sorted(causes.get(str(record.code), [])),
        "planned": sorted(planned.get(str(record.code), [])),
        "awaiting_review": sorted(waiting.get(str(record.code), [])),
    } for record in FailureModeRegistry.list_all()]


def render_md(rows: list[dict], *, show: bool | None = None) -> str:
    """The page; ``show`` (whether it names planned packages) defaults to the website's switch (:func:`show_planned`)."""
    show = show_planned() if show is None else show
    guarded = sum(1 for r in rows if r["guarded_by"])
    waiting = " (built, awaiting its certificate)"
    head = ["# Failure modes", "", "<!-- generated by tools/gen_failure_map.py from the installed code; do not edit -->",
            ""]
    if show:
        planned = sum(1 for r in rows if (r["planned"] or r["awaiting_review"]) and not r["guarded_by"])
        out = head + [
            "Every way of failing G6 names, the components that guard against it today, the ones whose own use can "
            "cause it, and the packages planned to guard it. A planned package guards nothing until it is in the "
            "library and declares the mode itself; one built in a vetted area guards nothing until its certificate "
            "is current.", "",
            f"{len(rows)} failure modes: {guarded} guarded by at least one component, {planned} planned only, "
            f"{len(rows) - guarded - planned} with no guard yet.", "",
            "| Failure mode | Code | Guarded by | Can be caused by | Planned in |", "|---|---|---|---|---|"]
    else:
        out = head + [
            "Every way of failing G6 names, the components in the library that guard against it today, and the ones "
            "whose own use can cause it. A component built in a vetted area guards nothing until its certificate is "
            "current.", "",
            f"{len(rows)} failure modes: {guarded} guarded by at least one component, {len(rows) - guarded} with no "
            "guard yet.", "",
            "| Failure mode | Code | Guarded by | Can be caused by | Built, awaiting its certificate |",
            "|---|---|---|---|---|"]
    for r in rows:
        later = ([f"`{x}`" for x in r["planned"]] if show else []) + [f"`{x}`{waiting}" for x in r["awaiting_review"]]
        cells = [", ".join(f"`{x}`" for x in r[key]) or "—" for key in ("guarded_by", "introduced_by")]
        cells.append(", ".join(later) or "—")
        out.append(f"| {r['title'].replace('|', chr(92) + '|')} | `{r['code']}` | " + " | ".join(cells) + " |")
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    rows = collect()
    outputs = {JSON_OUT: json.dumps(rows, indent=2) + "\n", MD_OUT: render_md(rows)}
    if "--check" in argv:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items()
                 if not p.is_file() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("out of date (run python tools/gen_failure_map.py): " + ", ".join(stale))
            return 1
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
