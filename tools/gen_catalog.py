"""Regenerate the component catalogue from the installed code (never edit the outputs by hand).

    python tools/gen_catalog.py           # write catalog/components.json and site/docs/components.md
    python tools/gen_catalog.py --check   # exit 1 if either is out of date (used by the test suite)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JSON_OUT = ROOT / "catalog" / "components.json"
MD_OUT = ROOT / "site" / "docs" / "components.md"


def collect() -> list[dict]:
    from g6.core import discovery
    from g6.core.maturity import maturity_reason
    from g6.core.registry import get_registry

    reg = get_registry()
    rows = []
    for name in reg.names():
        info = discovery.describe(name)
        cls = reg.get_class(name)
        rows.append({
            "name": name,
            "summary": info.get("summary", ""),
            "maturity": info.get("maturity") or "unlabelled",
            "maturity_reason": maturity_reason(cls) if cls else "",
            "surface": "python + cli + mcp" if cls else "python",
            "ops": info.get("ops", []),
            "requires": info.get("requires", []),
            "sensitive_ops": info.get("sensitive_ops", []),
            # "built, awaiting review" until its certificate is current (no person's review: DECISIONS #39)
            "vetting": (info.get("vetting") or {}).get("status"),
        })
    return rows


def render_md(rows: list[dict]) -> str:
    out = ["# Components", "",
           "<!-- generated by tools/gen_catalog.py from the installed code; do not edit -->", "",
           "Every component works on its own. *Requires* lists the other components it imports; "
           "*surface* says whether it can be called over the CLI and MCP (`g6 invoke`, `g6_invoke`) "
           "or only from Python.", "",
           "| Component | What it does | Surface | Ops | Requires |", "|---|---|---|---|---|"]
    for r in rows:
        ops = ", ".join(f"`{o}`" for o in r["ops"]) or "—"
        req = ", ".join(r["requires"]) or "—"
        summary = r["summary"].replace("|", "\\|")
        name = f"`{r['name']}`" + (" (built, awaiting its certificate)" if r.get("vetting") == "built, awaiting review"
                                   else "")
        out.append(f"| {name} | {summary} | {r['surface']} | {ops} | {req} |")
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    rows = collect()
    outputs = {JSON_OUT: json.dumps(rows, indent=2) + "\n", MD_OUT: render_md(rows)}
    if "--check" in argv:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items()
                 if not p.is_file() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("out of date (run python tools/gen_catalog.py): " + ", ".join(stale))
            return 1
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
